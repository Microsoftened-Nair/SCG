"""Empirical evaluation metrics and confusion matrix calculations for Supply Chain Guardian (SCG).

Conforms to IEEE Std 830-1998, RFC 2119, and SCG-SRS-PHASE-8 (REQ-P8-04, P8-06, P8-07, P8-08).
"""

from __future__ import annotations

from dataclasses import dataclass
from typing import Optional


@dataclass
class ConfusionMetrics:
    """Confusion matrix counts and derived empirical evaluation metrics."""

    tp: int
    fp: int
    fn: int
    tn: int
    precision: Optional[float]
    recall: Optional[float]
    f1_score: Optional[float]
    false_positive_rate: Optional[float]
    specificity: Optional[float]
    alert_reduction_pct: Optional[float]


def compute_metrics(
    tp: int,
    fp: int,
    fn: int,
    tn: int,
    baseline_alerts: Optional[int] = None,
) -> ConfusionMetrics:
    """Compute precision, recall, F1, FPR, specificity, and alert reduction.

    Per P8-07, P8-08, and P8-12:
    - Empty denominators MUST evaluate to None, never defaulting to 1.0 or 0.0.
    - Precision = tp / (tp + fp) if (tp + fp) > 0 else None
    - Recall = tp / (tp + fn) if (tp + fn) > 0 else None
    - F1 = 2 * P * R / (P + R) if (P is not None and R is not None and (P + R) > 0) else None
    - False Positive Rate = fp / (fp + tn) if (fp + tn) > 0 else None
    - Specificity = tn / (tn + fp) if (tn + fp) > 0 else None
    - Alert Reduction = max(0.0, 1.0 - (scg_alerts / baseline_alerts)) * 100.0 if baseline_alerts > 0 else None
      where scg_alerts = tp + fp.

    Args:
        tp: True positives count.
        fp: False positives count.
        fn: False negatives count.
        tn: True negatives count.
        baseline_alerts: Total alerts generated by baseline unpruned scanner (optional).

    Returns:
        ConfusionMetrics instance with computed metrics or None for empty denominators.
    """
    # Precision (P8-08)
    precision: Optional[float] = (
        float(tp) / float(tp + fp) if (tp + fp) > 0 else None
    )

    # Recall
    recall: Optional[float] = (
        float(tp) / float(tp + fn) if (tp + fn) > 0 else None
    )

    # F1 Score
    f1_score: Optional[float] = (
        (2.0 * precision * recall) / (precision + recall)
        if (precision is not None and recall is not None and (precision + recall) > 0.0)
        else None
    )

    # False Positive Rate (P8-07)
    false_positive_rate: Optional[float] = (
        float(fp) / float(fp + tn) if (fp + tn) > 0 else None
    )

    # Specificity
    specificity: Optional[float] = (
        float(tn) / float(tn + fp) if (tn + fp) > 0 else None
    )

    # Alert Reduction Percentage
    alert_reduction_pct: Optional[float] = None
    if baseline_alerts is not None and baseline_alerts > 0:
        scg_alerts = tp + fp
        reduction = max(0.0, 1.0 - (float(scg_alerts) / float(baseline_alerts)))
        alert_reduction_pct = reduction * 100.0

    return ConfusionMetrics(
        tp=tp,
        fp=fp,
        fn=fn,
        tn=tn,
        precision=precision,
        recall=recall,
        f1_score=f1_score,
        false_positive_rate=false_positive_rate,
        specificity=specificity,
        alert_reduction_pct=alert_reduction_pct,
    )
